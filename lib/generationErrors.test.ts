import { describe, it } from 'node:test';
import assert from 'node:assert/strict';
import {
  classifyGenerationError,
  describeGenerationError,
  isGenerationErrorCode,
} from './generationErrors.ts';

describe('classifyGenerationError', () => {
  // Message thật lấy từ analytics_events (04–10/2026).
  const cases: Array<[string, string]> = [
    ['Request payload too large. Please use a smaller image or compress before upload.', 'payload_too_large'],
    ['Backend error (HTTP 413): <html><head><title>413 Request Entity Too Large</title>', 'payload_too_large'],
    ['No image was generated by the model.', 'no_output'],
    ['Image blocked by the safety filter.', 'content_filter'],
    ['Load failed', 'network_error'],
    ['Failed to fetch', 'network_error'],
    ['File read failed: NotReadableError', 'file_read_failed'],
    ['Backend error (HTTP 504): upstream request timeout', 'timeout'],
    ['Request timed out waiting for the image generation server.', 'timeout'],
    ['{"error":{"code":503,"message":"This model is currently experiencing high demand.","status":"UNAVAILABLE"}}', 'service_unavailable'],
    ['{"error":{"code":503,"message":"Deadline expired before operation could complete.","status":"UNAVAILABLE"}}', 'service_unavailable'],
    ['{"error":{"code":500,"message":"Internal error encountered.","status":"INTERNAL"}}', 'server_error'],
    ['Backend returned non-JSON response (HTTP 502). Preview: <!DOCTYPE html>', 'server_error'],
    ["Unexpected token '<', \"<!DOCTYPE \"... is not valid JSON", 'server_error'],
    ['{"error":{"code":429,"message":"You exceeded your current quota","status":"RESOURCE_EXHAUSTED"}}', 'quota_exceeded'],
    ['Rate limit exceeded. Please wait a minute.', 'rate_limit'],
    ['{"error":{"code":400,"message":"Image size 512px is not supported for this model","status":"INVALID_ARGUMENT"}}', 'invalid_prompt'],
    ['{"error":{"code":404,"message":"models/gemini-3-flash-image-preview is not found for API version v1beta","status":"NOT_FOUND"}}', 'not_found'],
    ['The model or endpoint seedream-5-0-lite does not exist or you do not have access to it.', 'not_found'],
    ["Gemini API key missing. Please select an API key using the 'Select API Key' button or contact admin.", 'config_error'],
    ['Could not load the default credentials. Browse to https://cloud.google.com/docs/authentication', 'config_error'],
    ['{"error":{"code":400,"message":"API key not valid. Please pass a valid API key.","status":"INVALID_ARGUMENT"}}', 'config_error'],
    ['Lỗi API (403 Forbidden): Model này yêu cầu API Key trả phí (Paid)', 'forbidden'],
    ['An unknown error occurred.', 'unknown_error'],
    ['', 'unknown_error'],
  ];

  for (const [message, expected] of cases) {
    it(`${expected} ← ${message.slice(0, 60) || '(empty)'}`, () => {
      assert.equal(classifyGenerationError(message), expected);
    });
  }

  it('understands legacy slug error_codes (underscores instead of spaces)', () => {
    assert.equal(
      classifyGenerationError('request_payload_too_large_please_use_a_smaller_image_or_compress_before_upload_'),
      'payload_too_large'
    );
    assert.equal(classifyGenerationError('no_image_was_generated_by_the_model_'), 'no_output');
    assert.equal(classifyGenerationError('failed_to_fetch'), 'network_error');
  });

  it('passes known codes through unchanged', () => {
    for (const code of ['quota_exceeded', 'content_filter', 'file_read_failed', 'unknown_error']) {
      assert.equal(classifyGenerationError(code), code);
    }
  });
});

describe('describeGenerationError', () => {
  it('returns label, severity and source for a code', () => {
    assert.deepEqual(describeGenerationError('payload_too_large'), {
      code: 'payload_too_large',
      label: 'Payload Too Large (413)',
      severity: 'warning',
      source: 'user',
    });
  });

  it('attributes network errors to the client and provider errors to the system', () => {
    assert.equal(describeGenerationError('network_error').source, 'client');
    assert.equal(describeGenerationError('service_unavailable').source, 'system');
    assert.equal(describeGenerationError('no_output').source, 'system');
  });

  it('classifies raw legacy messages before describing them', () => {
    assert.equal(describeGenerationError('Failed to fetch').label, 'Network Error');
  });

  it('treats unknown errors as system / critical', () => {
    assert.deepEqual(describeGenerationError(undefined), {
      code: 'unknown_error',
      label: 'Unknown Error',
      severity: 'critical',
      source: 'system',
    });
  });
});

describe('isGenerationErrorCode', () => {
  it('accepts known codes only', () => {
    assert.equal(isGenerationErrorCode('timeout'), true);
    assert.equal(isGenerationErrorCode('Failed to fetch'), false);
  });
});
